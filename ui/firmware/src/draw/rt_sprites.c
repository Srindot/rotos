const char *const *rt_sprite_maneuver(uint8_t type, bool *mirror)
{
    if (!RN_ASSERT(mirror != NULL)) {
        return STRAIGHT;
    }
    *mirror = false;
    switch (type) {
    case RN_M_LEFT:
        return LEFT;
    case RN_M_RIGHT:
        *mirror = true;
        return LEFT;
    case RN_M_SLIGHT_LEFT:
    case RN_M_FORK_LEFT:
    case RN_M_RAMP_LEFT:
        return SLIGHT_LEFT;
    case RN_M_SLIGHT_RIGHT:
    case RN_M_FORK_RIGHT:
    case RN_M_RAMP_RIGHT:
        *mirror = true;
        return SLIGHT_LEFT;
    case RN_M_SHARP_LEFT:
        return SHARP_LEFT;
    case RN_M_SHARP_RIGHT:
        *mirror = true;
        return SHARP_LEFT;
    case RN_M_UTURN_LEFT:
        return UTURN_LEFT;
    case RN_M_UTURN_RIGHT:
        *mirror = true;
        return UTURN_LEFT;
    case RN_M_ROUNDABOUT_LEFT:
        return ROUNDABOUT;
    case RN_M_ROUNDABOUT_RIGHT:
        *mirror = true;
        return ROUNDABOUT;
    case RN_M_ARRIVE:
        return ARRIVE;
    default:  return STRAIGHT;
    }
}

const char *const *rt_sprite_weather(uint8_t wmo, bool is_day)
{
    if (wmo <= 1u) {
        return is_day ? W_SUN : W_MOON;
    }
    if (wmo == 2u) {
        return W_PARTLY;
    }
    if (wmo == 45u || wmo == 48u) {
        return W_FOG;
    }
    if (wmo >= 95u) {
        return W_STORM;
    }
    if ((wmo >= 51u && wmo <= 67u) || (wmo >= 80u && wmo <= 82u)) {
        return W_RAIN;
    }
    return W_CLOUD;
}

const char *const *rt_sprite_mascot(uint8_t mood)
{
    if (mood == RT_MOOD_HAPPY) {
        return MASCOT_HAPPY;
    }
    return (mood == RT_MOOD_BLINK) ? MASCOT_BLINK : MASCOT_IDLE;
}
