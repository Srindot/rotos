const char* weatherName(uint8_t c) {
    if (c == 0) return "CLEAR";
    if (c == 1) return "MOSTLY CLEAR";
    if (c == 2) return "PARTLY CLOUDY";
    if (c == 3) return "CLOUDY";
    if (c == 45 || c == 48) return "FOG";
    if (c >= 51 && c <= 57) return "DRIZZLE";
    if (c == 65 || c == 82) return "HEAVY RAIN";
    if (c >= 61 && c <= 67) return "RAIN";
    if (c >= 80 && c <= 82) return "SHOWERS";
    if (c >= 95) return "THUNDERSTORM";
    return "CLOUDY";
}

static void drawSprite2(Canvas& cv, int x, int y, const char* const* s, int scale) {
    for (int r = 0; r < 16; ++r)
        for (int c = 0; c < 16; ++c) {
            char ch = s[r][c];
            if (ch == '#') cv.fillRect(x + c * scale, y + r * scale, scale, scale, C_TEXT);
            else if (ch == '+') cv.fillRect(x + c * scale, y + r * scale, scale, scale, C_ACCENT);
        }
}

void drawWeatherIcon(Canvas& cv, int x, int y, uint8_t c, bool isDay, int scale) {
    const char* const* s = W_CLOUD;
    if (c <= 1) s = isDay ? W_SUN : W_MOON;
    else if (c == 2) s = W_PARTLY;
    else if (c == 45 || c == 48) s = W_FOG;
    else if (c >= 95) s = W_STORM;
    else if ((c >= 51 && c <= 67) || (c >= 80 && c <= 82)) s = W_RAIN;
    drawSprite2(cv, x, y, s, scale);
}

// ── Flyover arrows ────────────────────────────────────────────────────
void drawFlyoverArrow(Canvas& cv, int x, int y, bool up, uint8_t color) {
    static const char* A[7] = {"...#...", "..###..", ".#####.", "#######", "..###..", "..###..", "..###.."};
    for (int r = 0; r < 7; ++r)
        for (int c = 0; c < 7; ++c)
            if (A[up ? r : 6 - r][c] == '#') cv.pixel(x + c, y + r, color);
}

