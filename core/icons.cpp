void drawManeuverIcon(Canvas& cv, int x, int y, ManeuverType t, int scale, uint8_t color) {
    const char* const* s = STRAIGHT;
    bool mirror = false;
    switch (t) {
        case M_LEFT: s = LEFT; break;
        case M_RIGHT: s = LEFT; mirror = true; break;
        case M_SLIGHT_LEFT: case M_FORK_LEFT: case M_RAMP_LEFT: s = SLIGHT_LEFT; break;
        case M_SLIGHT_RIGHT: case M_FORK_RIGHT: case M_RAMP_RIGHT: s = SLIGHT_LEFT; mirror = true; break;
        case M_SHARP_LEFT: s = SHARP_LEFT; break;
        case M_SHARP_RIGHT: s = SHARP_LEFT; mirror = true; break;
        case M_UTURN_LEFT: s = UTURN_LEFT; break;
        case M_UTURN_RIGHT: s = UTURN_LEFT; mirror = true; break;
        case M_ROUNDABOUT_LEFT: s = ROUNDABOUT; break;
        case M_ROUNDABOUT_RIGHT: s = ROUNDABOUT; mirror = true; break;
        case M_ARRIVE: s = ARRIVE; break;
        default: break;
    }
    for (int r = 0; r < 16; ++r)
        for (int c = 0; c < 16; ++c)
            if (s[r][mirror ? 15 - c : c] == '#') cv.fillRect(x + c * scale, y + r * scale, scale, scale, color);
}

