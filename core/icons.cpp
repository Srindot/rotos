void drawMascot(Canvas& cv, int x, int y, int mood, int scale) {
    const char* const* s = mood == 2 ? MASCOT_HAPPY : (mood == 1 ? MASCOT_BLINK : MASCOT_IDLE);
    for (int r = 0; r < 16; ++r)
        for (int c = 0; c < 16; ++c) {
            uint8_t col;
            switch (s[r][c]) {
                case 's': col = C_SHADOW; break;
                case 'a': col = C_ACCENT; break;
                case 'w': col = C_TEXT; break;
                case 'p': col = C_SHADOW; break;
                case 'h': col = C_HILITE; break;
                default: continue;
            }
            cv.fillRect(x + c * scale, y + r * scale, scale, scale, col);
        }
}

